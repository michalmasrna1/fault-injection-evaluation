from abc import ABC, abstractmethod
from itertools import combinations
from typing import Iterable


class LowEntropyBytesGenerator(ABC):
    @abstractmethod
    def generate(self) -> Iterable[tuple[bytes, int]]:
        pass


class HighestLowestByteBytesGenerator(LowEntropyBytesGenerator):
    def generate(self) -> Iterable[tuple[bytes, int]]:
        """
        Generate bytes with bits only set in the highest and the lowest byte.
        """
        for upper_num_bits in range(0, 8):
            for upper_bits in combinations(range(8), upper_num_bits):
                for lower_num_bits in range(0, 8):
                    for lower_bits in combinations(range(8), lower_num_bits):
                        faulted_bytes = 0
                        for bit in upper_bits:
                            faulted_bytes |= 1 << bit
                        for bit in lower_bits:
                            faulted_bytes |= 1 << (bit + 248)
                        yield faulted_bytes.to_bytes(32, 'little'), upper_num_bits + lower_num_bits


class FaultedBytesGenerator(ABC):
    @abstractmethod
    def generate(self, original_bytes: bytes) -> Iterable[tuple[bytes, int]]:
        pass


class ShiftedBytesGenerator(FaultedBytesGenerator):
    """
    Generate bytes by shifting the original bytes any number of bits to the
    left or right, filling the remaining bits with the filler.
    Shift by 0 is skipped to avoid yielding the original bytes.
    The filler represents the data that is "around" the original bytes.
    It should be as long as the bytes that will be generated.

    As we do not know whether the library interprets the bytes as big or little
    endian, we try both for the bytes and also for the filler.

    Example:
    Original: 01001101
    Filler: 10011001
    The full "view" would be 10011001|01001101|10011001
    Generated bytes (what is between | |):
    10011001|01001101|10011001    -    10011001|01001101|10011001
    -------------------------------------------------------------
    00110010|10011011|0011001     1     1001100|10100110|11001100
    01100101|00110110|011001      2      100110|01010011|01100110
                ...               ...               ...
    01001101|10011001|            8            |10011001|01001101
    """

    def __init__(self, filler: bytes):
        self.filler = filler

    def generate(self, original_bytes: bytes) -> Iterable[tuple[bytes, int]]:
        if not len(original_bytes) == len(self.filler):
            raise ValueError(
                f"The original bytes must be the same length as the filler."
                f" Filler length: {len(self.filler)}, original bytes length: {len(original_bytes)}"
            )

        size_bits = len(original_bytes) * 8
        for original_endian in ['little', 'big']:
            for filler_endian in ['little', 'big']:
                # Assertions for typing purposes.
                assert original_endian == "big" or original_endian == "little"
                assert filler_endian == "big" or filler_endian == "little"

                original_bytes_int = int.from_bytes(original_bytes, byteorder=original_endian)
                filler_int = int.from_bytes(self.filler, byteorder=filler_endian)
                for shift in range(1, size_bits):
                    shifted_left = (original_bytes_int << shift) & ((1 << size_bits) - 1)
                    shifted_right = original_bytes_int >> shift
                    shifted_left_filled = shifted_left | (filler_int & ((1 << shift) - 1))
                    shifted_right_filled = shifted_right | (filler_int & (((1 << shift) - 1) << (size_bits - shift)))

                    entropy = size_bits - shift
                    yield shifted_left_filled.to_bytes(len(original_bytes), original_endian), entropy
                    yield shifted_right_filled.to_bytes(len(original_bytes), original_endian), entropy


class MaskGenerator(ABC):
    @abstractmethod
    def generate(self) -> Iterable[bytes]:
        """
        Generate masks that can be applied to the original bytes.
        The original bytes will retain the bits corresponding to
        the bits of the mask set to 1.
        The entropy of the mask is always the number of 1s,
        so it does not have to be calculated here.
        """


class BlockMaskGenerator(MaskGenerator):
    def __init__(self, block_size_bits: int, original_size_bits: int):
        self.block_size_bits = block_size_bits
        self.original_size_bits = original_size_bits

    def generate(self) -> Iterable[bytes]:
        """
        Generate masks representing `block_size` consecutive ones
        shifted through the bytes. From block_size 16 and total size 64
        bytes, this would be:
        0x000000000000ffff
        0x00000000ffff0000
        0x0000ffff00000000
        0xffff000000000000
        """
        unshifted_mask: int = 2**self.block_size_bits - 1
        for i in range(self.original_size_bits // self.block_size_bits):
            yield (unshifted_mask << (i * self.block_size_bits)).to_bytes(self.original_size_bits // 8, 'little')


class BeginningEndMaskGenerator(MaskGenerator):
    def __init__(self, original_size_bits: int):
        self.original_size_bits = original_size_bits

    def generate(self) -> Iterable[bytes]:
        # Any number of bits from the start + any number of bits from the end
        for bits_start in range(0, self.original_size_bits):
            # Leave a space of at least one faulted bit, otherwise you use the full key
            for bits_end in range(0, self.original_size_bits - bits_start):
                if bits_start + bits_end == 0:
                    continue
                start_of_mask = ((1 << self.original_size_bits) - 1) ^ (1 << self.original_size_bits - bits_start) - 1
                end_of_mask = (1 << bits_end) - 1
                yield (start_of_mask | end_of_mask).to_bytes(self.original_size_bits // 8, 'big')
                yield (start_of_mask | end_of_mask).to_bytes(self.original_size_bits // 8, 'little')


# Which classes of faulted keys we want might be dependant on the library,
# but perhaps they can all use all of them by default.
def generate_low_entropy_keys(original_key: bytes) -> Iterable[tuple[bytes, int]]:
    """
    Returns tuples of (low_entropy_key, entropy), where the entropy
    represents how many bits were used from the original key.
    """
    fault_masks: set[bytes] = set()  # A set because we only care about unique masks.
    key_size_bits = len(original_key) * 8

    for block_size_bits in [8, 32, 64, 128]:
        mask_generator = BlockMaskGenerator(block_size_bits, key_size_bits)
        fault_masks.update(mask_generator.generate())

    fault_masks.update(BeginningEndMaskGenerator(key_size_bits).generate())

    for mask in fault_masks:
        num_bits = bin(int.from_bytes(mask, byteorder='little')).count('1')
        faulted_key_bytes = bytes(a & b for a, b in zip(original_key, mask))
        yield faulted_key_bytes, num_bits

    # Shifted keys filled with 0s.
    yield from ShiftedBytesGenerator(b'\x00' * len(original_key)).generate(original_key)
    # Shifted keys filled with 1s.
    yield from ShiftedBytesGenerator(b'\xff' * len(original_key)).generate(original_key)

    yield from HighestLowestByteBytesGenerator().generate()


def generate_faulted_outputs(original_output: bytes, buffer_content: bytes) -> Iterable[tuple[bytes, int]]:
    """
    Returns tuples of (faulted_output, entropy), where the entropy
    represents how many bits were used from the original output.

    This should represent cases when the output copying loop was manipulated.
    Not all Generators are used as not all of them make sense as opposed to
    in generate_low_entropy_keys.

    The buffer_content represents the data that is in the output buffer
    at the beginning of the execution. For the thesis, this is probably:
    0xecc25519ecc25519ecc25519ecc25519ecc25519ecc25519ecc25519ecc25519
    """
    fault_masks: set[bytes] = set()  # A set because we only care about unique masks.
    output_size_bits = len(original_output) * 8

    for block_size_bits in [8, 32, 64, 128]:
        mask_generator = BlockMaskGenerator(block_size_bits, output_size_bits)
        fault_masks.update(mask_generator.generate())

    fault_masks.update(BeginningEndMaskGenerator(output_size_bits).generate())

    fillers = [
        b'\x00' * len(original_output),  # All 0s
        b'\xff' * len(original_output),  # All 1s
        buffer_content  # The original buffer content
    ]

    for filler in fillers:
        for mask in fault_masks:
            num_bits = bin(int.from_bytes(mask, byteorder='little')).count('1')
            # For each bit, if the mask has it set to 1, take it from the original output,
            # else from the filler.
            faulted_output_bytes = bytes(
                ((a & b) | (c & ~b))
                for a, b, c in zip(original_output, mask, filler)
            )

            print(faulted_output_bytes.hex())
            yield faulted_output_bytes, num_bits

        yield from ShiftedBytesGenerator(filler).generate(original_output)
